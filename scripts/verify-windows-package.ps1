    Fail 'WebView2 Evergreen Runtime is unavailable; install the matching native WebView2 runtime'
}

function Wait-ForMainWindow(
    [System.Diagnostics.Process] $Process,
    [int] $TimeoutSeconds
) {
    $Deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSeconds)
    while ([DateTime]::UtcNow -lt $Deadline) {
        $Process.Refresh()
        if ($Process.HasExited) {
            Fail "application exited before the Overseer window appeared (exit code $($Process.ExitCode))"
        }
        if ($Process.MainWindowHandle -ne [IntPtr]::Zero) {
            $Window = [System.Windows.Automation.AutomationElement]::FromHandle($Process.MainWindowHandle)
            if ($null -ne $Window -and $Window.Current.Name -eq $WindowTitle) {
                return $Window
            }
        }
        Start-Sleep -Milliseconds 200
    }
    Fail "real Overseer window was not observed within $TimeoutSeconds seconds"
}

function Find-TopLevelWindow([string] $Name) {
    $Root = [System.Windows.Automation.AutomationElement]::RootElement
    $Windows = $Root.FindAll(
        [System.Windows.Automation.TreeScope]::Children,
        [System.Windows.Automation.Condition]::TrueCondition
    )
    foreach ($Window in $Windows) {
        try {
            if ($Window.Current.Name -eq $Name -and -not $Window.Current.IsOffscreen) {
                return $Window
            }
        } catch {
            # A window may disappear while UI Automation enumerates it.
        }
    }
    return $null
}

function Wait-ForTopLevelWindow([string] $Name, [int] $TimeoutSeconds) {
    $Deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSeconds)
    while ([DateTime]::UtcNow -lt $Deadline) {
        $Window = Find-TopLevelWindow $Name
        if ($null -ne $Window) {
            return $Window
        }
        Start-Sleep -Milliseconds 200
    }
    Fail "native window was not observed: $Name"
}

function Find-DescendantByProperty(
    $Root,
    $Property,
    [object] $Value,
    [System.Windows.Automation.ControlType] $ControlType = $null
) {
    $Condition = [System.Windows.Automation.PropertyCondition]::new($Property, $Value)
    if ($null -ne $ControlType) {
        $Conditions = [System.Windows.Automation.Condition[]] @(
            $Condition,
            [System.Windows.Automation.PropertyCondition]::new(
                [System.Windows.Automation.AutomationElement]::ControlTypeProperty,
                $ControlType
            )
        )
        $Condition = [System.Windows.Automation.AndCondition]::new($Conditions)
    }
    return $Root.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $Condition)
}

function Find-ValueElementByAutomationId($Root, [string] $AutomationId) {
    $Container = Find-DescendantByProperty $Root `
        ([System.Windows.Automation.AutomationElement]::AutomationIdProperty) $AutomationId
    if ($null -eq $Container) {
        return $null
    }
    $Pattern = $null
    if ($Container.TryGetCurrentPattern([System.Windows.Automation.ValuePattern]::Pattern, [ref] $Pattern)) {
        return $Container
    }
    $Candidates = $Container.FindAll(
        [System.Windows.Automation.TreeScope]::Descendants,
        [System.Windows.Automation.Condition]::TrueCondition
    )
    foreach ($Candidate in $Candidates) {
        $Pattern = $null
        if ($Candidate.TryGetCurrentPattern([System.Windows.Automation.ValuePattern]::Pattern, [ref] $Pattern)) {
            return $Candidate
        }
    }
    return $null
}

function Wait-ForDescendantByProperty(
    $Root,
    $Property,
    [object] $Value,
    [System.Diagnostics.Process] $Process,
    [int] $TimeoutSeconds,
    [System.Windows.Automation.ControlType] $ControlType = $null
) {
    $Deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSeconds)
    while ([DateTime]::UtcNow -lt $Deadline) {
        $Process.Refresh()
        if ($Process.HasExited) {
            Fail "application exited before UI Automation exposed $Value (exit code $($Process.ExitCode))"
        }
        try {
            $Element = Find-DescendantByProperty $Root $Property $Value $ControlType
            if ($null -ne $Element) {
                return $Element
            }
        } catch {
            # WebView2 may refresh its accessibility tree while the frontend starts.
        }
        Start-Sleep -Milliseconds 200
    }
    Fail "UI Automation element was not observed within $TimeoutSeconds seconds: $Value"
}

function Find-DescendantByNamePrefix($Root, [string] $Prefix) {
    $Elements = $Root.FindAll(
        [System.Windows.Automation.TreeScope]::Descendants,
        [System.Windows.Automation.Condition]::TrueCondition
    )
    foreach ($Element in $Elements) {
        try {
            if ($Element.Current.Name.StartsWith($Prefix, [StringComparison]::Ordinal)) {
                return $Element
            }
        } catch {
            # The accessibility tree may refresh during enumeration.
        }
    }
    return $null
}

