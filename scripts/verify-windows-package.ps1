function Test-PlayerListener([bool] $ExpectedOpen) {
    $Client = [System.Net.Sockets.TcpClient]::new()
    try {
        $Connection = $Client.ConnectAsync('127.0.0.1', 3690)
        $Connected = $Connection.Wait(250) -and $Client.Connected
