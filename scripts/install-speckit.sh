#!/usr/bin/env bash

set -euo pipefail

required_variables=(
	SPECKIT_VERSION
	SPECKIT_COMPANION_VERSION
	SPECKIT_BROWNFIELD_VERSION
	SPECKIT_BUGFIX_VERSION
	SPECKIT_FEATURE_NUMBERING_VERSION
)
for variable_name in "${required_variables[@]}"; do
	if [[ -z "${!variable_name:-}" ]]; then
		printf 'Missing required environment variable: %s\n' "${variable_name}" >&2
		exit 1
	fi
done

readonly spec_kit_tag="v${SPECKIT_VERSION#v}"
readonly spec_kit_source="git+https://github.com/github/spec-kit.git@${spec_kit_tag}"
readonly companion_url="https://github.com/alfredoperez/speckit-companion/releases/download/speckit-ext-v${SPECKIT_COMPANION_VERSION}/companion-${SPECKIT_COMPANION_VERSION}.zip"
readonly brownfield_url="https://github.com/Quratulain-bilal/spec-kit-brownfield/archive/refs/tags/v${SPECKIT_BROWNFIELD_VERSION}.zip"
readonly bugfix_url="https://github.com/Quratulain-bilal/spec-kit-bugfix/archive/refs/tags/v${SPECKIT_BUGFIX_VERSION}.zip"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/.." && pwd)"
readonly script_dir repo_root

cd "${repo_root}"

if ! command -v uv >/dev/null 2>&1; then
	printf 'uv is required. Install it from https://docs.astral.sh/uv/getting-started/installation/\n' >&2
	exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
	printf 'jq is required. Install it from https://jqlang.org/download/\n' >&2
	exit 1
fi

if [[ ! -f .speckit/feature-numbering/extension.yml ]]; then
	printf 'Missing local extension: .speckit/feature-numbering/extension.yml\n' >&2
	exit 1
fi

local_extension_version="$(awk '
	/^extension:/ { in_extension = 1; next }
	in_extension && /^  version:/ {
		gsub(/["'\''[:space:]]/, "", $2)
		print $2
		exit
	}
' .speckit/feature-numbering/extension.yml)"
readonly local_extension_version
if [[ "${local_extension_version}" != "${SPECKIT_FEATURE_NUMBERING_VERSION}" ]]; then
	printf 'Pinned feature-numbering version %s does not match local manifest version %s.\n' \
		"${SPECKIT_FEATURE_NUMBERING_VERSION}" "${local_extension_version:-missing}" >&2
	exit 1
fi

printf 'Installing GitHub Spec Kit %s...\n' "${spec_kit_tag}"
uv tool install --force specify-cli --from "${spec_kit_source}"

uv_bin_dir="$(uv tool dir --bin)"
specify_bin="${uv_bin_dir}/specify"
readonly uv_bin_dir specify_bin
if [[ ! -x "${specify_bin}" ]]; then
	printf 'Specify CLI was installed, but %s is not executable.\n' "${specify_bin}" >&2
	exit 1
fi

# Prints the hash that the integration manifests in directory $1 record for
# the managed file $2, or nothing when no manifest tracks it.
recorded_hash() {
	jq -r --arg path "$2" '.files[$path] // empty' "$1"/*.manifest.json
}

# Refreshes the core skills, templates, and scripts that Spec Kit manages in
# this project when they were generated by a release other than the pinned
# one. A forced upgrade overwrites customized managed files, so they are
# restored afterwards and listed when the new release renders them
# differently, because upstream changes to them must be ported by hand.
upgrade_project_files() {
	local project_version
	project_version="$(jq -r '.version // empty' .specify/integration.json)"
	if [[ "${project_version}" == "${spec_kit_tag#v}" ]]; then
		return
	fi

	upgrade_backup_dir="$(mktemp -d)"
	trap 'rm -rf -- "${upgrade_backup_dir}"' EXIT
	mkdir -p "${upgrade_backup_dir}/manifests" "${upgrade_backup_dir}/files"
	cp .specify/integrations/*.manifest.json "${upgrade_backup_dir}/manifests/"

	local customized_files path
	customized_files="$("${specify_bin}" integration status --json | jq -r '.manifests[].modified_files[]')"
	while IFS= read -r path; do
		[[ -n "${path}" ]] || continue
		mkdir -p "${upgrade_backup_dir}/files/$(dirname "${path}")"
		cp -p "${path}" "${upgrade_backup_dir}/files/${path}"
	done <<<"${customized_files}"

	printf 'Upgrading project files from Spec Kit v%s to %s...\n' "${project_version}" "${spec_kit_tag}"
	"${specify_bin}" integration upgrade --force </dev/null

	local changed_upstream=()
	while IFS= read -r path; do
		[[ -n "${path}" ]] || continue
		cp -p "${upgrade_backup_dir}/files/${path}" "${path}"
		if [[ "$(recorded_hash "${upgrade_backup_dir}/manifests" "${path}")" != "$(recorded_hash .specify/integrations "${path}")" ]]; then
			changed_upstream+=("${path}")
		fi
	done <<<"${customized_files}"

	if ((${#changed_upstream[@]} > 0)); then
		printf '\nKept project customizations that Spec Kit %s renders differently:\n' "${spec_kit_tag}"
		printf '  %s\n' "${changed_upstream[@]}"
		printf 'Port the upstream changes that apply: https://github.com/github/spec-kit/compare/v%s...%s\n\n' \
			"${project_version}" "${spec_kit_tag}"
	fi
}

install_extension() {
	local extension_id="$1"
	local extension_url="$2"
	local priority="$3"

	# The Specify CLI asks to confirm every --from URL. These URLs are built
	# from the versions pinned in Taskfile.yml, so the prompt is answered here;
	# the CLI still prints its untrusted-source warning.
	"${specify_bin}" extension add "${extension_id}" \
		--from "${extension_url}" \
		--force \
		--priority "${priority}" <<<y
}

# Upgrade before installing extensions: the integration upgrade re-renders
# extension skills, and reinstalling the extensions renders them back.
upgrade_project_files
install_extension companion "${companion_url}" 10
install_extension brownfield "${brownfield_url}" 10
install_extension bugfix "${bugfix_url}" 10
"${specify_bin}" extension add --dev --force --priority 5 .speckit/feature-numbering
"${script_dir}/normalize-speckit-skills.sh"

printf '\nInstalled Spec Kit and project extensions:\n'
"${specify_bin}" version
"${specify_bin}" extension list
printf '\nRestart Claude Code so it reloads generated skills.\n'
